import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { isIP } from 'node:net';
const args=process.argv.slice(2);
if(args.length!==2||args[0]!=='--url')throw new Error('Usage: npm run assets:configure -- --url https://YOUR_HOST/miniprogram-assets');
const url=new URL(args[1]);
if(!['https:','http:'].includes(url.protocol)||url.username||url.password||url.search||url.hash)throw new Error('Use an HTTP(S) URL without credentials/query/fragment');
const config={baseUrl:url.href.replace(/\/+$/,'')};
if(url.protocol==='https:'&&isIP(url.hostname))config.allowIpHttps=true;
await writeFile(resolve(import.meta.dirname,'../miniprogram/config/assets.js'),'// Generated by npm run assets:configure. No credentials belong in this file.\nmodule.exports = '+JSON.stringify(config,null,2)+';\n');
console.log('Updated image URL; recompile and re-upload the mini program to apply it.');
