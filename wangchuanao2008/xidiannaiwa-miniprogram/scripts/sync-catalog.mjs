import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const catalog = JSON.parse(await readFile(resolve(root, 'content/catalog.json'), 'utf8'));
await writeFile(resolve(root, 'miniprogram/data/catalog.js'), '// Generated by npm run catalog:sync. Edit content/catalog.json instead.\nmodule.exports = ' + JSON.stringify(catalog) + ';\n');
console.log(`Synced ${catalog.works.length} artworks. Run npm run check next.`);
