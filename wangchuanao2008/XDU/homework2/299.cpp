#include <stdio.h>

int main() {
    int I;
    scanf("%d", &I);

    int b200;   /* 奖金 ×200 后的值：6 档费率都乘 200 就全是整数了 */
    if (I <= 100000) {
        b200 = I * 20;                              /* 10%  = 20/200 */
    } else if (I <= 200000) {
        b200 = 10000 * 200 + (I - 100000) * 15;     /* 7.5% = 15/200 */
    } else if (I <= 400000) {
        b200 = 17500 * 200 + (I - 200000) * 10;     /* 5%   = 10/200 */
    } else if (I <= 600000) {
        b200 = 27500 * 200 + (I - 400000) * 6;      /* 3%   = 6/200  */
    } else if (I <= 1000000) {
        b200 = 33500 * 200 + (I - 600000) * 3;      /* 1.5% = 3/200  */
    } else {
        b200 = 39500 * 200 + (I - 1000000) * 2;     /* 1%   = 2/200  */
    }

    printf("%d\n", b200 / 200);   /* 除以 200 还原成元，整数除法舍去小数部分 */
    return 0;
}
